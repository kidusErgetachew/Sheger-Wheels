function booking(
  id: string,
  carId: string,
  renterId: string,
  ownerId: string,
  startOffset: number,
  endOffset: number,
  status: DemoBooking["status"],
): DemoBooking {
  const car = cars.find((item) => item.id === carId);
  if (!car) throw new Error(`Seed car ${carId} was not found.`);

  const days = endOffset - startOffset;
  const subtotal = days * car.pricePerDay;
  const fee = Math.round(subtotal * 0.05);

  return {
    id,
    carId,
    renterId,
    ownerId,
    startDate: dateOffset(startOffset),
    endDate: dateOffset(endOffset),
    days,
    pricePerDay: car.pricePerDay,
    subtotal,
    fee,
    total: subtotal + fee,
    transactionReference: null,
    paymentStatus: status === "confirmed" ? "held" : "unpaid",
    status,
    createdAt: timestampOffset(startOffset - 7),
    updatedAt: timestampOffset(startOffset - 7),
  };
}

